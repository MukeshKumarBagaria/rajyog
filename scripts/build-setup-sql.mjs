#!/usr/bin/env node
/**
 * Builds supabase/setup.sql — every migration (in order) followed by the seed —
 * so a fresh Supabase project can be set up with ONE paste into the SQL Editor.
 *
 *   npm run db:setup-sql            regenerate the file
 *   node scripts/build-setup-sql.mjs --check   fail if the file is out of date
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'supabase', 'migrations');
const target = join(root, 'supabase', 'setup.sql');

const parts = [
  `-- ════════════════════════════════════════════════════════════════════════════
-- Rajyog · one-shot setup for a NEW Supabase project
--
-- GENERATED by scripts/build-setup-sql.mjs from supabase/migrations/*.sql and
-- supabase/seed.sql — do not edit by hand.
--
-- Paste the whole file into Dashboard → SQL Editor and click Run. The editor
-- runs it as a single transaction: if anything fails, nothing is applied.
-- Run it once. (Using the CLI instead? \`supabase db push\` applies the same
-- migrations; then run seed.sql.)
-- ════════════════════════════════════════════════════════════════════════════
`,
];

for (const file of readdirSync(migrationsDir).filter((f) => f.endsWith('.sql')).sort()) {
  parts.push(`\n-- ▶ migration: ${file}\n\n${readFileSync(join(migrationsDir, file), 'utf8').trim()}\n`);
}
parts.push(`\n-- ▶ seed.sql\n\n${readFileSync(join(root, 'supabase', 'seed.sql'), 'utf8').trim()}\n`);
const output = parts.join('');

if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== output) {
    console.error('supabase/setup.sql is out of date — run: npm run db:setup-sql');
    process.exit(1);
  }
  console.log('supabase/setup.sql is up to date');
} else {
  writeFileSync(target, output);
  console.log(`wrote ${target}`);
}
